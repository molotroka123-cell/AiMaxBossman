/* English form of a fixed server phrase, or null. A review note appended to a cleared check ("... -> снято проверкой: who (date): note") keeps the human's note as written. */
function srvT(s) {
  const cut = s.indexOf(" -> снято проверкой: ");
  if (cut > 0) {
    const head = srvT(s.slice(0, cut));
    return head == null ? null : head + " -> cleared by review: " + s.slice(cut + " -> снято проверкой: ".length);
  }
  for (const [rx, en] of SRV_RX) {
    const m = rx.exec(s);
    if (m) return en.replace(/\$(\d)/g, (x, i) => (m[+i] == null ? "" : m[+i]));
  }
  return null;
}
