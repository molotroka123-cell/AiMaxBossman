def main():
    print(f"Creating and validating {len(SKILLS_DATA)} skills in {SKILLS_DIR}...")
    errors_total = 0

    for item in SKILLS_DATA:
        slug = item["slug"]
        s_dir = SKILLS_DIR / slug
        s_dir.mkdir(parents=True, exist_ok=True)
        s_file = s_dir / "SKILL.md"

        content = f"""---
name: {slug}
description: "{item['description']}"
metadata:
  owner: bossman-curated
  version: "2.0"
---

{item['body'].strip()}
"""
        s_file.write_text(content, encoding="utf-8")

        # Validation
        sk = parse_skill(s_file, SKILLS_DIR)
        manifest_res = validate_manifest(sk)
        policy_res = [v for v in scan_policy(sk.body) if v.critical]

        errs = manifest_res["errors"]
        if errs or policy_res:
            print(f"ERROR on {slug}: manifest_errors={errs}, policy_critical={policy_res}")
            errors_total += len(errs) + len(policy_res)
        else:
            print(f"[OK] {slug}: manifest valid, 0 policy violations")

    # Now discover with SkillLibrary
    lib = SkillLibrary([SKILLS_DIR], SKILLS_DIR)
    found = lib.discover()
    print(f"\nSkillLibrary discovered {len(found)} skills total in {SKILLS_DIR}")
    print(f"Library errors: {lib.errors}")

    if errors_total == 0 and len(lib.errors) == 0:
        print("\nALL 17 SKILLS CREATED AND VALIDATED WITH 0 ERRORS!")
    else:
        print(f"\nFAILED with {errors_total} errors!")
        sys.exit(1)

if __name__ == "__main__":
    main()
