"""Output-tree hygiene for the Windows bundle (findings of the 12.10 release scan).

Standard-library helpers that ``build_windows_bundle.py`` runs on the assembled output
tree BEFORE ``MANIFEST.json`` is computed, so that the archive

* does not carry the builder's own paths (Playwright's ``browser/.links/<sha>`` cache link
  files hold the absolute path of the build-time driver package, and the build output
  directory / the user profile must not appear in any shipped text file);
* does not carry zero-byte ``*.whl`` placeholders inside ``site-packages``;
* lists every file it contains in ``MANIFEST.json`` (``MANIFEST.json`` and ``SHA256SUMS``
  cannot list themselves and are the only exemptions).

Every check here raises ``RuntimeError`` naming the offending files; nothing is
downgraded to a warning. The reports returned for ``MANIFEST.json`` carry counts only,
never the paths that were searched for.

One deliberate exemption: files that the RECORD of an installed THIRD-PARTY distribution
lists are the contents of a hash-pinned upstream wheel. Upstream wheels built on GitHub's
Windows runners carry that runner's profile path in ``numpy/__config__.py``,
``*.dist-info/DELVEWHEEL`` and the like, which would be indistinguishable from a leak of
the profile of a builder that is itself such a runner. They are therefore exempt from the
USER PROFILE check only; the build output directory is searched for everywhere.
"""
from __future__ import annotations

import csv
import io
import os
import posixpath
import re
import shutil
from pathlib import Path
from typing import Collection, Iterable, Mapping

LINKS_DIR = ".links"
OUTPUT_LABEL = "build output directory"
PROFILE_LABEL = "user profile directory"
MANIFEST_SELF = ("MANIFEST.json", "SHA256SUMS")
# Text/JSON the leak scan reads. Larger files and anything with a NUL byte in the first
# bytes (executables, weights, images, bytecode, fonts) are skipped, not guessed at.
TEXT_SCAN_MAX_BYTES = 4 * 1024 * 1024
SNIFF_BYTES = 8192
MIN_NEEDLE_CHARS = 6
REPORT_LIMIT = 20


# ------------------------------------------------------------------ removals

def drop_playwright_links(browser: Path) -> list[str]:
    """Delete ``browser/.links``: Playwright's cache link files hold the BUILD-time driver path.

    The directory is regenerated by ``playwright install`` on the machine that runs it and
    nothing in the product reads it, so it is removed rather than rewritten. Returns the
    names of the removed link files.
    """
    links = browser / LINKS_DIR
    if not links.is_dir():
        return []
    names = sorted(entry.name for entry in links.iterdir())
    shutil.rmtree(links)
    return names


def zero_byte_wheels(site_packages: Path) -> list[str]:
    """Every empty ``*.whl`` under ``site-packages`` (posix paths relative to it)."""
    if not site_packages.is_dir():
        return []
    return sorted(path.relative_to(site_packages).as_posix()
                  for path in site_packages.rglob("*.whl")
                  if path.is_file() and path.stat().st_size == 0)


def drop_zero_byte_wheels(site_packages: Path) -> list[str]:
    """Remove empty ``*.whl`` files from ``site-packages`` and assert that none remain."""
    removed = zero_byte_wheels(site_packages)
    for relative in removed:
        (site_packages / relative).unlink()
    left = zero_byte_wheels(site_packages)
    if left:
        raise RuntimeError(f"zero-byte wheel files remain in site-packages: {left[:REPORT_LIMIT]}")
    return removed


# ------------------------------------------------------------- path leak scan

def path_needles(path: Path | str) -> list[str]:
    """Lower-cased text spellings of one path: backslash, forward slash and JSON-escaped."""
    base = str(path).strip().replace("/", "\\").rstrip("\\")
    forms = {base, base.replace("\\", "\\\\"), base.replace("\\", "/")}
    return sorted(form.lower() for form in forms if len(form) >= MIN_NEEDLE_CHARS)


def _labelled_needles(builder_paths: Mapping[str, Path | str]) -> dict[str, list[str]]:
    return {label: needles for label, needles in
            ((label, path_needles(path)) for label, path in builder_paths.items()) if needles}


def normalize_name(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def distribution_files(root: Path, names: Iterable[str]) -> set[str]:
    """Files (posix paths relative to ``root``) that the RECORD of the named distributions lists."""
    wanted = {normalize_name(name) for name in names}
    site = root.joinpath("runtime", "Lib", "site-packages")
    found: set[str] = set()
    if not wanted or not site.is_dir():
        return found
    base = site.relative_to(root).as_posix()
    for info in site.glob("*.dist-info"):
        if normalize_name(info.name[:-len(".dist-info")].rpartition("-")[0]) not in wanted:
            continue
        record = info / "RECORD"
        if not record.is_file():
            continue
        text = record.read_text(encoding="utf-8", errors="replace")
        for row in csv.reader(io.StringIO(text)):
            if row and row[0] and not row[0].endswith(".dist-info/RECORD"):
                found.add(posixpath.normpath(posixpath.join(base, row[0])))
    return found


def find_path_leaks(root: Path, builder_paths: Mapping[str, Path | str], *,
                    max_bytes: int = TEXT_SCAN_MAX_BYTES,
                    exempt: Mapping[str, Collection[str]] | None = None) -> dict:
    """Search small text files under ``root`` for any spelling of the given builder paths.

    ``exempt`` maps a label to relative paths that are not searched for THAT label.
    Returns ``{"leaks": [(relative path, label), ...], "scanned": n, "skipped_binary": n,
    "skipped_large": n, "exempt_matches": n}``. Matching is case-insensitive (Windows paths are).
    """
    labelled = _labelled_needles(builder_paths)
    exempt = exempt or {}
    leaks: list[tuple[str, str]] = []
    scanned = skipped_binary = skipped_large = exempt_matches = 0
    if not labelled:
        return {"leaks": leaks, "scanned": 0, "skipped_binary": 0, "skipped_large": 0, "exempt_matches": 0}
    encoded = {label: [needle.encode("utf-8") for needle in needles]
               for label, needles in labelled.items()}
    for directory, _dirs, names in os.walk(root):
        for name in names:
            path = Path(directory) / name
            try:
                size = path.stat().st_size
                if size == 0:
                    continue
                if size > max_bytes:
                    skipped_large += 1
                    continue
                with path.open("rb") as stream:
                    head = stream.read(SNIFF_BYTES)
                    if b"\x00" in head:  # binary: the rest of the file is never read
                        skipped_binary += 1
                        continue
                    data = head + stream.read(max_bytes)
            except OSError:
                continue
            scanned += 1
            lowered = data.lower()
            relative = path.relative_to(root).as_posix()
            for label, needles in encoded.items():
                if any(needle in lowered for needle in needles):
                    if relative in exempt.get(label, ()):
                        exempt_matches += 1
                        continue
                    leaks.append((relative, label))
                    break
    return {"leaks": sorted(leaks), "scanned": scanned, "skipped_binary": skipped_binary,
            "skipped_large": skipped_large, "exempt_matches": exempt_matches}


def assert_no_path_leaks(root: Path, builder_paths: Mapping[str, Path | str], *,
                         max_bytes: int = TEXT_SCAN_MAX_BYTES,
                         exempt: Mapping[str, Collection[str]] | None = None) -> dict:
    """Fail when a shipped text file contains the build output directory or the user profile."""
    report = find_path_leaks(root, builder_paths, max_bytes=max_bytes, exempt=exempt)
    leaks = report.pop("leaks")
    if leaks:
        shown = "; ".join(f"{relative} ({label})" for relative, label in leaks[:REPORT_LIMIT])
        more = f" (+{len(leaks) - REPORT_LIMIT} more)" if len(leaks) > REPORT_LIMIT else ""
        raise RuntimeError("the bundle output carries the builder's own paths in text files; "
                           f"it must not be archived: {shown}{more}")
    return report


# ------------------------------------------------------------ manifest coverage

def tree_files(root: Path) -> list[str]:
    """Every file below ``root`` as a sorted posix path relative to it."""
    return sorted(path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_file())


def unlisted_files(root: Path, listed: Iterable[str]) -> list[str]:
    """Files present in the tree that the manifest does not list (self-entries exempt)."""
    known = set(listed) | set(MANIFEST_SELF)
    return [relative for relative in tree_files(root) if relative not in known]


def assert_manifest_complete(root: Path, files: Iterable[Mapping[str, object]]) -> int:
    """Every file except MANIFEST.json/SHA256SUMS is in ``files``, and every entry exists."""
    listed = [str(item["path"]) for item in files]
    unlisted = unlisted_files(root, listed)
    absent = sorted(path for path in set(listed) if not (root / path).is_file())
    if unlisted or absent:
        raise RuntimeError("MANIFEST.json does not match the output tree: "
                           f"unlisted={unlisted[:REPORT_LIMIT]} missing={absent[:REPORT_LIMIT]}")
    return len(listed)


# ----------------------------------------------------------------- composite

def finalize_tree(out: Path, builder_paths: Mapping[str, Path | str], *,
                  third_party_distributions: Iterable[str] = ()) -> dict:
    """Everything that must be true of the tree before the manifest is computed.

    ``third_party_distributions`` are the installed distributions whose RECORD-listed files are
    exempt from the user-profile search (see the module docstring); the build output
    directory is searched for everywhere.
    """
    links = drop_playwright_links(out / "browser")
    wheels = drop_zero_byte_wheels(out / "runtime" / "Lib" / "site-packages")
    third_party = distribution_files(out, third_party_distributions)
    scan = assert_no_path_leaks(out, builder_paths, exempt={PROFILE_LABEL: third_party})
    return {"playwright_links_removed": len(links), "zero_byte_wheels_removed": wheels,
            "path_leak_scan": {"result": "PASS", "third_party_files_exempt_from_profile_check": len(third_party),
                               **scan}}
