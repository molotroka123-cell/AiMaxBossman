/* ============================================================
   chat/theme-boot.js — тема чата до первой отрисовки.

   Обычный (не модульный) скрипт в <head> chat.html: выполняется до
   отрисовки <body>, поэтому светлая тема не мигает тёмной. Раньше это был
   встроенный <script>; политика безопасности страницы (CSP script-src
   'self') встроенные скрипты запрещает, поэтому он вынесен в файл.
   Остальное оформление ставит main.js.
   ============================================================ */
(function bootChatTheme() {
  try {
    if (window.localStorage.getItem('bcc.chat.theme') === 'light') document.documentElement.dataset.theme = 'light';
  } catch (e) {
    /* приватный режим: тема по умолчанию (тёмная) */
  }
}());
