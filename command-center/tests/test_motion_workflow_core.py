def _ffmpeg(*args: str) -> None:
    cmd = [FFMPEG, "-hide_banner", "-v", "error", "-y", *args]
    done = subprocess.run(cmd, capture_output=True, text=True)
    assert done.returncode == 0, done.stderr


def _texture(seed: int, w: int, h: int, seconds: float, *, base: int = 128, amp: int = 100) -> str:
    """A static, deterministic, band-limited noise picture as a lavfi source (no time dependence)."""
    k1, k2 = 12.9898 + seed * 0.37, 78.233 + seed * 0.91
    return (f"nullsrc=s={w}x{h}:r={FPS}:d={seconds},format=gray,"
            f"geq=lum='{base}+{amp}*(abs(mod(sin(X*{k1}+Y*{k2})*43758.5453,1))-0.5)',gblur=sigma=1.2,"
            "format=yuv420p")


ENC = ["-c:v", "libx264", "-crf", "16", "-preset", "veryfast", "-pix_fmt", "yuv420p"]


@pytest.fixture(scope="module")
def clips(tmp_path_factory) -> dict[str, Path]:
    if not (FFMPEG and FFPROBE):
        pytest.skip("ffmpeg/ffprobe not available")
    d = tmp_path_factory.mktemp("mw_clips")
    out: dict[str, Path] = {}

    def make(name: str, *args: str) -> None:
        path = d / f"{name}.mp4"
        _ffmpeg(*args, *ENC, str(path))
        out[name] = path

    # 6 flat shots with very different luma -> 5 hard cuts at frames 25, 45, 75, 90, 115
    levels = [("0xEBEBEB", 1.0), ("0x101010", 0.8), ("0xB4B4B4", 1.2), ("0x1E1E1E", 0.6),
              ("0xDCDCDC", 1.0), ("0x3C3C3C", 0.9)]
    inputs: list[str] = []
    for color, seconds in levels:
        inputs += ["-f", "lavfi", "-i", f"color=c={color}:s=320x240:r={FPS}:d={seconds}"]
    graph = "".join(f"[{i}:v]" for i in range(len(levels))) + f"concat=n={len(levels)}:v=1:a=0,format=yuv420p"
    make("cuts", *inputs, "-filter_complex", graph)

    # a strong step (score ~0.55) followed by a weak one (~0.21): which cuts exist depends on the threshold
    make("soft",
         "-f", "lavfi", "-i", f"color=c=0x606060:s=320x240:r={FPS}:d=1",
         "-f", "lavfi", "-i", f"color=c=0xA0A0A0:s=320x240:r={FPS}:d=1",
         "-f", "lavfi", "-i", f"color=c=0xB8B8B8:s=320x240:r={FPS}:d=1",
         "-filter_complex", "[0:v][1:v][2:v]concat=n=3:v=1:a=0,format=yuv420p")

    # a 2-frame flash between two long shots
    make("flash",
         "-f", "lavfi", "-i", f"color=c=0xEBEBEB:s=320x240:r={FPS}:d=1.0",
         "-f", "lavfi", "-i", f"color=c=0x101010:s=320x240:r={FPS}:d=0.08",
         "-f", "lavfi", "-i", f"color=c=0xB4B4B4:s=320x240:r={FPS}:d=1.0",
         "-filter_complex", "[0:v][1:v][2:v]concat=n=3:v=1:a=0,format=yuv420p")

    make("static", "-f", "lavfi", "-i", _texture(1, 320, 240, 3))
    make("pan", "-f", "lavfi", "-i", _texture(2, 960, 240, 3), "-vf", "crop=320:240:x='t*50':y=0")
    make("tilt", "-f", "lavfi", "-i", _texture(2, 320, 960, 3), "-vf", "crop=320:240:x=0:y='t*50'")
    make("zoom", "-f", "lavfi", "-i", _texture(3, 640, 480, 3),
         "-vf", "scale=w='trunc(320*(1+0.12*t)/2)*2':h='trunc(240*(1+0.12*t)/2)*2':eval=frame:flags=bilinear,"
                "crop=320:240")
    make("handheld", "-f", "lavfi", "-i", _texture(4, 400, 300, 3),
         "-vf", "crop=320:240:x='40+6*sin(n*2.3)+4*sin(n*4.1)':y='30+5*sin(n*1.7)+3*sin(n*3.9)'")
    make("panstop", "-f", "lavfi", "-i", _texture(2, 960, 240, 4),
         "-vf", "crop=320:240:x='clip((t-1)*50,0,75)':y=0")
    make("black", "-f", "lavfi", "-i", f"color=c=black:s=320x240:r={FPS}:d=2")
    make("fade",
         "-f", "lavfi", "-i", _texture(5, 320, 240, 2, base=60, amp=90),
         "-f", "lavfi", "-i", _texture(6, 320, 240, 2, base=190, amp=90),
         "-filter_complex", "[0:v]fade=t=out:st=1:d=1[a];[1:v]fade=t=in:st=0:d=1[b];[a][b]concat=n=2:v=1:a=0")
    make("dissolve",
         "-f", "lavfi", "-i", _texture(5, 320, 240, 2, base=60, amp=90),
         "-f", "lavfi", "-i", _texture(6, 320, 240, 2, base=190, amp=90),
         "-filter_complex", "[0:v][1:v]xfade=transition=fade:duration=1:offset=1")

    # a bright shot dissolves into a DARK scene (luma ~18, not black) that then cuts to a bright shot:
    # dark UI must not be read as a fade through black
    make("darkscene",
         "-f", "lavfi", "-i", _texture(5, 320, 240, 2, base=130, amp=90),
         "-f", "lavfi", "-i", f"color=c=0x121212:s=320x240:r={FPS}:d=2",
         "-f", "lavfi", "-i", _texture(6, 320, 240, 1, base=170, amp=60),
         "-filter_complex", "[0:v][1:v]xfade=transition=fade:duration=0.4:offset=1[ab];"
                            "[ab][2:v]concat=n=2:v=1:a=0")

    # 6 s clip with a click track: clicks every 0.5 s in 0.25-2.75 s and 4.25-5.75 s, silence 2.75-4.25 s
    rate = 16000
    samples = [0.0] * int(rate * 6.0)
    beats: list[float] = []
    for start, stop in ((0.25, 2.75), (4.25, 5.75)):
        t = start
        while t < stop:
            i0 = int(t * rate)
            for k in range(int(0.03 * rate)):
                samples[i0 + k] += 0.7 * math.sin(2 * math.pi * 1000 * k / rate) * (1 - k / (0.03 * rate))
            beats.append(t)
            t += 0.5
    wav = d / "clicks.wav"
    with wave.open(str(wav), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(rate)
        handle.writeframes(b"".join(struct.pack("<h", int(max(-1.0, min(1.0, v)) * 32000)) for v in samples))
    out["clicks_truth"] = beats  # type: ignore[assignment]
    path = d / "audio.mp4"
    _ffmpeg("-f", "lavfi", "-i", _texture(1, 320, 240, 6), "-i", str(wav), "-map", "0:v", "-map", "1:a",
            *ENC, "-c:a", "aac", "-shortest", str(path))
    out["audio"] = path
    return out


