def test_a_lock_held_by_a_live_process_blocks_until_it_times_out(tmp_path):
    st = Store(tmp_path / "data", lock_timeout=0.4, lock_stale=60.0)
    pid = _seed(st)
    sleeper = subprocess.Popen([sys.executable, "-c", "import time; time.sleep(60)"])
    try:
        lock = st.root / pid / ".lock"
        lock.write_text(json.dumps({"pid": sleeper.pid, "token": "live", "ts": time.time()}), encoding="utf-8")
        with pytest.raises(StoreBusyError):
            st.edit(pid, [{"op": "set_notes", "notes": "blocked"}])
        old = time.time() - 3600                                          # ... until it is older than stale
        os.utime(lock, (old, old))
        st.edit(pid, [{"op": "set_notes", "notes": "taken over"}])
        assert st.get_project(pid)["notes"] == "taken over"
    finally:
        sleeper.kill()
        sleeper.wait()


