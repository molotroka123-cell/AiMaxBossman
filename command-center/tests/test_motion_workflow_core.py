def test_concurrent_writers_never_lose_an_update(tmp_path):
    st = Store(tmp_path / "data")
    pid = _seed(st)
    errors: list[BaseException] = []

    def work(i: int) -> None:
        try:
            st.edit(pid, [{"op": "set_notes", "notes": f"writer {i}"}], author=f"w{i}")
        except BaseException as exc:                                    # pragma: no cover - reported below
            errors.append(exc)

    threads = [threading.Thread(target=work, args=(i,)) for i in range(8)]
    for t in threads:
        t.start()
    for t in threads:
        t.join(30)
    assert errors == []
    versions = [h["version"] for h in st.history(pid, limit=100)]
    assert versions == list(range(10, 0, -1))                           # 2 setup + 8 writers, contiguous
    assert {h["author"] for h in st.history(pid, limit=100)[:8]} == {f"w{i}" for i in range(8)}
    assert st.verify(pid) == []


