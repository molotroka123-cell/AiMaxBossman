@needs_ffmpeg
def test_text_boxes_come_from_a_pluggable_ocr_callback(clips):
    seen = []

    def fake_ocr(frame_path: str, t: float):
        seen.append((Path(frame_path).is_file(), t))
        return [{"text": "SALE", "box": [10, 20, 100, 30], "conf": 91.2}, {"text": "", "box": [0, 0, 1, 1]},
                {"bad": True}]

    result = analyze.analyze_video(clips["cuts"], ocr=fake_ocr)
    first = result["scenes"][0]["text"]
    assert first["status"] == "measured"
    assert first["method"] == "fake_ocr"
    assert first["boxes"][0] == {"t": first["boxes"][0]["t"], "text": "SALE", "box": [10, 20, 100, 30], "conf": 91.2}
    assert all(len(b) == 4 for b in (x["box"] for x in first["boxes"]))
    assert seen and all(ok for ok, _ in seen)
    assert result["scenes"][0]["elements"]["text"]["detected"]["boxes"] == len(first["boxes"])


