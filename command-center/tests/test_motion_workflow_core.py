@needs_numpy
def test_opencv_and_numpy_phase_correlation_agree():
    cv2 = analyze._load_cv2()
    if cv2 is None:
        pytest.skip("OpenCV not importable")
    np = NUMPY
    rng = np.random.default_rng(3)
    h, w = 96, 128
    base = rng.random((h, w)).astype(np.float32) * 255
    fy, fx = np.fft.fftfreq(h)[:, None], np.fft.fftfreq(w)[None, :]
    base = np.real(np.fft.ifft2(np.fft.fft2(base) * np.exp(-(fx ** 2 + fy ** 2) * 200))).astype(np.float32)
    moved = np.real(np.fft.ifft2(np.fft.fft2(base) * np.exp(-2j * np.pi * (fx * 3.0 + fy * -2.0)))).astype(np.float32)
    results = []
    for module in (None, cv2):
        est = analyze._MotionEstimator(np, h, w, module)
        est.feed(base)
        results.append(est.feed(moved))
    for key, truth in (("dx", 3.0), ("dy", -2.0)):
        assert results[0][key] == pytest.approx(truth, abs=0.4)       # numpy FFT
        assert results[1][key] == pytest.approx(truth, abs=0.7)       # OpenCV: same sign, coarser sub-pixel


