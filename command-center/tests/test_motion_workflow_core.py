def test_running_job_becomes_interrupted_at_startup_and_resumes_from_next_scene(tmp_path):
    first = Store(tmp_path / "data")
    pid, jid = _ready_job(first)
    first.job_start_preview(pid, jid)
    for sid in ("s001", "s002", "s003"):
        first.job_complete_scene(pid, jid, sid)
    first.job_finish_preview(pid, jid)
    first.job_start_render(pid, jid)
    first.job_complete_scene(pid, jid, "s001")
    first.job_complete_scene(pid, jid, "s002")
    assert first.get_job(pid, jid)["state"] == "RENDER_RUNNING"
    # the process dies here; a new Store instance is the restarted backend
    second = Store(tmp_path / "data")
    assert second.recovery_report["interrupted"] == [
        {"project_id": pid, "job_id": jid, "last_completed_scene": "s002"}]
    job = second.get_job(pid, jid)
    assert job["state"] == "INTERRUPTED"
    assert job["interrupted"]["phase"] == "render"
    assert job["interrupted"]["last_completed_scene"] == "s002"
    assert job["interrupted"]["resume_from_scene"] == "s003"
    assert job["phases"]["render"]["completed"] == ["s001", "s002"]
    second.job_resume(pid, jid)
    with pytest.raises(JobStateError, match="next scene is 's003'"):
        second.job_complete_scene(pid, jid, "s001")           # already done: resume does not redo scenes
    resumed = second.get_job(pid, jid)
    assert resumed["state"] == "RENDER_RUNNING" and resumed["attempt"] == 2 and resumed["next_scene"] == "s003"
    second.job_complete_scene(pid, jid, "s003")
    assert second.job_finish_render(pid, jid)["state"] == "RENDER_DONE"


